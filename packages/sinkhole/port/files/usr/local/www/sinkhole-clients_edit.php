/**
 * Sinkhole Client Editor - Posted Device Identifier Rows.
 *
 * Reads the numeric suffixes generated by pfSense's repeatable Form groups while
 * preserving invalid values for form redisplay.
 *
 * @param array $post - Submitted form values.
 *
 * @return list<array{type: string, value: string, interface: string, mapping: string}>
 *
 * @since 1.3.0
 */
function sinkholeClientEditorPostedDeviceIdentifierRows(array $post): array
{
    $positions = [];

    foreach (array_keys($post) as $key) {
        if (is_string($key) && preg_match('/^device_identifier_type([0-9]+)$/D', $key, $matches) === 1) {
            $positions[(int) $matches[1]] = true;
        }
    }

    ksort($positions, SORT_NUMERIC);
    $rows = [];

    foreach (array_keys($positions) as $position) {
        $type = (string) ($post['device_identifier_type' . $position] ?? '');
        $value = (string) ($post['device_identifier' . $position] ?? '');
        $interface = '';
        $mapping = (string) ($post['device_static_mapping' . $position] ?? '');

        if ($type === ScopeConfiguration::DEVICE_STATIC_MAPPING) {
            $mappingParts = explode('|', $mapping, 2);

            if (count($mappingParts) === 2) {
                [$interface, $value] = $mappingParts;
            } else {
                $value = '';
            }
        }

        $rows[] = [
            'type' => $type,
            'value' => $value,
            'interface' => $interface,
            'mapping' => $mapping,
        ];
    }

    return $rows;
}

/**
 * Sinkhole Client Editor - Validate Posted Device Identifiers.
 *
 * Each failure is wrapped with its one-based row number so the form points to the
 * exact repeated row that needs attention.
 *
 * @param array $post - Submitted form values.
 * @param list<array> $staticMappings - Current DHCP static mappings.
 *
 * @return list<array{type: string, value: string, interface: string}>
 *
 * @since 1.3.0
 */
function sinkholeClientEditorDeviceIdentifiers(array $post, array $staticMappings): array
{
    $rows = sinkholeClientEditorPostedDeviceIdentifierRows($post);

    if ($rows === []) {
        throw new ValidationException('device_identifiers_required');
    }

    $identifiers = [];
    $usedIdentifiers = [];

    foreach ($rows as $position => $row) {
        try {
            if (
                $row['type'] === ScopeConfiguration::DEVICE_STATIC_MAPPING
                && count(explode('|', $row['mapping'], 2)) !== 2
            ) {
                throw new ValidationException('select_dhcp_static_mapping');
            }

            $identifier = ScopeConfiguration::normalizeDeviceIdentifierRow($row, $staticMappings);
            $identifierKey = ScopeConfiguration::deviceIdentifierKey($identifier);

            if (isset($usedIdentifiers[$identifierKey])) {
                throw new ValidationException('device_identifier_duplicate_in_device');
            }

            $identifiers[] = $identifier;
            $usedIdentifiers[$identifierKey] = true;
        } catch (ValidationException $validationException) {
            throw new ValidationException('device_identifier_row_error', [
                $position + 1,
                pfsensePackageSinkholeThrowableMessage($validationException),
            ]);
        }
    }

    return $identifiers;
}

/**
 * Sinkhole Client Editor - Device Identifier Rows For Display.
 *
 * Accepts normalized, persisted repeated, and legacy single-identifier shapes so
 * a malformed saved row can still be repaired.
 *
 * @param array|null $editing - Edited device row.
 *
 * @return list<array{type: string, value: string, interface: string, mapping: string}>
 *
 * @since 1.3.0
 */
function sinkholeClientEditorDeviceIdentifierRows(?array $editing): array
{
    $emptyRow = [
        'type' => ScopeConfiguration::DEVICE_IP,
        'value' => '',
        'interface' => '',
        'mapping' => '',
    ];

    if ($editing === null) {
        return [$emptyRow];
    }

    if (array_key_exists('identifiers', $editing)) {
        $rows = ScopeConfiguration::unwrapRepeatedItems($editing['identifiers']);
    } elseif (
        array_key_exists('identifier_type', $editing)
        || array_key_exists('identifier', $editing)
        || array_key_exists('interface', $editing)
    ) {
        $rows = [[
            'type' => $editing['identifier_type'] ?? '',
            'value' => $editing['identifier'] ?? '',
            'interface' => $editing['interface'] ?? '',
        ]];
    } else {
        $rows = [];
    }

    if (!is_array($rows)) {
        $rows = [];
    } elseif ($rows !== [] && !array_is_list($rows)) {
        $rows = [$rows];
    }

    $displayRows = [];

    foreach ($rows as $row) {
        if (!is_array($row)) {
            continue;
        }

        $type = is_string($row['type'] ?? null) ? $row['type'] : ScopeConfiguration::DEVICE_IP;
        $value = is_string($row['value'] ?? null) ? $row['value'] : '';
        $interface = is_string($row['interface'] ?? null) ? $row['interface'] : '';
        $mapping = is_string($row['mapping'] ?? null)
            ? $row['mapping']
            : (($type === ScopeConfiguration::DEVICE_STATIC_MAPPING)
                ? $interface . '|' . $value
                : '');
        $displayRows[] = [
            'type' => $type,
            'value' => $value,
            'interface' => $interface,
            'mapping' => $mapping,
        ];
    }

    return ($displayRows === []) ? [$emptyRow] : $displayRows;
}

/**
 * Sinkhole Client Editor - Kept Blocking Settings.
 *
 * Clients edits only the definition. The lists and allowed domains Blocking owns
 * are carried over; a repaired row keeps only the values that are still valid.
 *
 * @param array|null $source - Existing valid or invalid row.
 * @param array<string, array> $lists - Configured lists.
 *
 * @return array{lists: list<string>, allowed_domains: list<string>}
 *
 * @since 1.3.0
 */
function sinkholeClientEditorKeptBlocking(?array $source, array $lists): array
{
    $sourceLists = ScopeConfiguration::unwrapRepeatedItems($source['lists'] ?? []);
    $keptLists = [];

    foreach (is_array($sourceLists) ? $sourceLists : [] as $listIdentifier) {
        if (is_string($listIdentifier) && isset($lists[$listIdentifier])) {
            $keptLists[$listIdentifier] = true;
        }
    }

    $sourceAllowed = ScopeConfiguration::unwrapRepeatedItems($source['allowed_domains'] ?? []);
    $allowedResult = DomainParser::normalizeAllowedDomainValues(
        is_array($sourceAllowed) ? $sourceAllowed : [],
    );

    return [
        'lists' => array_keys($keptLists),
        'allowed_domains' => $allowedResult['domains'],
    ];
}

/**
 * Sinkhole Client Editor - Apply Configuration.
