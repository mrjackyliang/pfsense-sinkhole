        $editing = ($clientType === 'network')
            ? ($networks[$identifier] ?? null)
            : ($devices[$identifier] ?? null);

        if ($editing === null) {
            throw new ValidationException(($clientType === 'network') ? 'network_missing' : 'device_missing');
        }

        $sourceRow = $editing;
    }
} catch (Throwable $throwable) {
    $actionMessage = pfsensePackageSinkholeThrowableMessage($throwable);
    $actionClass = 'danger';
    $identifier = '';
    $invalidPosition = null;
    $sourceRow = null;
